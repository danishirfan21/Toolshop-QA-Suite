import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

interface Case {
  id: string;
  title: string;
  priority: string;
  automation: 'Automate' | 'Keep manual';
  file: string;
}

const root = process.cwd();
const casesDir = join(root, 'docs', 'test-cases');
const testsDir = join(root, 'tests');
const ID = /TC-[A-Z]+-\d{3}/;

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

const posix = (path: string) => relative(root, path).split('\\').join('/');
const errors: string[] = [];

function readCases(): Case[] {
  const cases: Case[] = [];
  for (const file of walk(casesDir).filter((f) => f.endsWith('.md'))) {
    const text = readFileSync(file, 'utf8');
    for (const block of text.split(/^# Test case: /m).slice(1)) {
      const field = (name: string) => block.match(new RegExp(`^\\| ${name} \\| (.*?) \\|\\s*$`, 'm'))?.[1].trim() ?? '';
      const id = field('ID');
      const automation = field('Automation');
      if (!ID.test(id)) errors.push(`${posix(file)}: a case has no valid ID (got "${id}")`);
      if (automation !== 'Automate' && automation !== 'Keep manual') errors.push(`${id}: Automation must be "Automate" or "Keep manual" (got "${automation}")`);
      cases.push({ id, title: field('Title'), priority: field('Priority'), automation: automation as Case['automation'], file: posix(file) });
    }
  }
  return cases;
}

// Spec title -> ID. A title starts the first string argument of test(...).
function readSpecs(): Map<string, string[]> {
  const specs = new Map<string, string[]>();
  for (const file of walk(testsDir).filter((f) => f.endsWith('.spec.ts'))) {
    const text = readFileSync(file, 'utf8');
    for (const match of text.matchAll(/\btest(?:\.(?:only|skip|fixme|fail))?\(\s*(['"`])(.*?)\1/g)) {
      const found = match[2].match(ID);
      if (!found) {
        errors.push(`${posix(file)}: test "${match[2]}" has no case ID`);
        continue;
      }
      specs.set(found[0], [...(specs.get(found[0]) ?? []), posix(file)]);
    }
  }
  return specs;
}

const cases = readCases();
const specs = readSpecs();
const known = new Set<string>();

for (const c of cases) {
  if (known.has(c.id)) errors.push(`${c.id}: defined more than once`);
  known.add(c.id);
}
for (const [id, files] of specs) {
  if (!known.has(id)) errors.push(`${files.join(', ')}: references unknown case ${id}`);
  if ((specs.get(id)?.length ?? 0) > 1) errors.push(`${id}: referenced by more than one test (${files.join(', ')})`);
}

const rows = cases.map((c) => {
  const files = specs.get(c.id);
  let status: string;
  if (c.automation === 'Automate') {
    status = files ? 'Automated' : 'MISSING SPEC';
    if (!files) errors.push(`${c.id}: marked Automate but no spec references it`);
  } else {
    status = 'Manual';
    if (files) errors.push(`${c.id}: marked Keep manual but ${files.join(', ')} references it`);
  }
  return `| ${c.id} | ${c.title} | ${c.priority} | ${files ? files.join(', ') : '-'} | ${status} |`;
});

const automated = cases.filter((c) => c.automation === 'Automate').length;
const out = [
  '# Traceability',
  '',
  'Generated by `npm run traceability` from docs/test-cases/*.md and the case IDs in spec titles. Do not edit by hand.',
  '',
  `Cases: ${cases.length}. Automate: ${automated}. Keep manual: ${cases.length - automated}.`,
  '',
  '| Case | Title | Priority | Spec file | Status |',
  '| --- | --- | --- | --- | --- |',
  ...rows,
  '',
].join('\n');
writeFileSync(join(root, 'docs', 'traceability.md'), out);

console.log(`cases=${cases.length} automate=${automated} manual=${cases.length - automated} specs_with_ids=${specs.size}`);
if (errors.length) {
  console.error(errors.map((e) => `ERROR ${e}`).join('\n'));
  process.exit(1);
}
